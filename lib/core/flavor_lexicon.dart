List<FlavorLexiconEntry> _buildLexicon() {
  final seen = <String>{};
  final entries = <FlavorLexiconEntry>[];
  void addAll(List<String> words, int weight) {
    for (final word in words) {
      if (word.isEmpty || !seen.add(word)) continue;
      entries.add(FlavorLexiconEntry(
        word,
        weight,
        replacement: flavorReplacements[word],
      ));
    }
  }

  addAll(_highWeight, 3);
  addAll(_mediumWeight, 2);
  addAll(_lowWeight, 1);
  return List<FlavorLexiconEntry>.unmodifiable(entries);
}

